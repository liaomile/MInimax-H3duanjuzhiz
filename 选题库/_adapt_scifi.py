def apply_map(text: str) -> str:
    for a, b in FIX_GARBLED:
        text = text.replace(a, b)
    for a, b in REPLACES:
        text = text.replace(a, b)
    # 书名元数据常见英文残留
    text = text.replace("Ao Jian Tian Qiong", NEW_NOVEL)
    text = text.replace("aojian", "liehe")
    return text


