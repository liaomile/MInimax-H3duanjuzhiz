def up(*keys, audios=None):
    lines = []
    for i, k in enumerate(keys, 1):
        lines.append(f"@图片{i} = {A[k]}")
    if audios:
        for i, name in enumerate(audios, 1):
            lines.append(f"（建议）@音频{i} = 音色_{name}.wav")
    return "\n".join(lines)

