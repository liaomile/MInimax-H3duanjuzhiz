def write_outline(show_dir, title, meta_lines, episodes, spec):
    p = ROOT / show_dir / "整剧大纲.md"
    rows = "\n".join([f"| {e['ep']:02d} | {e['title']} | {e['hook']} | 5 |" for e in episodes])
    text = f"""# {title}整剧大纲（完整版）

{meta_lines}

## 本地生产规格（RTX 5000 16GB）

| 项 | 值 |
|----|----|
| 总集数 | **{len(episodes)} 集** |
| 每集镜头 | **5 镜** |
| 单镜时长 | **8 秒成片**（约 0.65MP · 9:16 · 关Turbo · 12–20步） |
| 单集素材 | 约 40 秒 → 剪辑到 **60–80 秒** |
| 工作流 | ComfyUI MiniMax H3 **R2V** |

{spec}

## 全集聚焦表

| 集 | 标题 | 结尾钩子 | 镜数 |
|----|------|----------|------|
{rows}

## 说明

每集目录：`第XX集/单集剧本.md` + `镜01–05_本地成片_H3提示词.txt` + `上传清单.txt`
"""
    p.write_text(text, encoding="utf-8")


def write_episode(ep_data):
    show, ep = ep_data["show"], ep_data["ep"]
    d = ROOT / show / f"第{ep:02d}集"
    d.mkdir(parents=True, exist_ok=True)
    # script
    rows = []
    for i, s in enumerate(ep_data["shots"], 1):
        # extract dialogue hint from tl
        rows.append(f"| {i:02d} | 8s | 见提示词 | {s['core'][:40]}… | 见成片提示词 |")
    md = f"""# 第{ep:02d}集 · {ep_data['title']}

| 字段 | 内容 |
|------|------|
| 本集目标 | {ep_data['title']} |
| 出场 | {ep_data['cast']} |
| 场景 | {ep_data['scene']} |
| 结尾钩子 | {ep_data['hook']} |
| 镜数 | 5（本地成片各8秒） |

## 分镜表

| 镜 | 秒 | 说明 | 事件摘要 | 提示词文件 |
|----|----|------|----------|------------|
""" + "\n".join(
        f"| {i:02d} | 8s | 成片 | 见下 | `镜{i:02d}_本地成片_H3提示词.txt` |"
        for i in range(1, 6)
    ) + f"""

## 本集事件节拍

{chr(10).join(f'{i}. {s["core"]}' for i,s in enumerate(ep_data['shots'],1))}

## 生成顺序

1. 打开 `上传清单.txt` 按序传图  
2. 依次跑镜01→05 **本地成片**  
3. 拼接 → 超分 1080×1920 → 字幕  
"""
    (d / "单集剧本.md").write_text(md, encoding="utf-8")
    # prompts
    for i, s in enumerate(ep_data["shots"], 1):
        (d / f"镜{i:02d}_本地成片_H3提示词.txt").write_text(render_prompt(s), encoding="utf-8")
    # upload list - parse first shot uploads
    (d / "上传清单.txt").write_text(
        f"【第{ep:02d}集 · {ep_data['title']}】\n\n按镜01提示词顶部的【上传顺序】点选文件。\n整集尽量固定同一套锁脸图，不要中途换底图。\n\n生成：镜01–05 本地成片（8秒）。\n钩子：{ep_data['hook']}\n",
        encoding="utf-8",
    )


