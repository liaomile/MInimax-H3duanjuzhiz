def up(imgs, auds=None):
    lines = [f"@图片{i} = {p}" for i, p in enumerate(imgs, 1)]
    if auds:
        lines += [f"（建议）@音频{i} = 音色_{n}.wav" for i, n in enumerate(auds, 1)]
    return "\n".join(lines)


def refs_text(parts):
    return "\n".join(parts)


