def write_ep(ep, title, hook, shots):
    d = ROOT / f"第{ep:02d}集"
    d.mkdir(parents=True, exist_ok=True)
    rows = []
    for i, s in enumerate(shots, 1):
        text = prompt(up(s["imgs"], s["auds"]), s["refs"], s["event"], s["tl"], s["sound"])
        (d / f"镜{i:02d}_本地成片_H3提示词.txt").write_text(text, encoding="utf-8")
        # extract first dialogue-ish line for table
        rows.append(f"| {i:02d} | 8s | {s['event'][:40]} | `镜{i:02d}_本地成片_H3提示词.txt` |")
    md = f"""# 第{ep:02d}集 · {title}

| 字段 | 内容 |
|------|------|
| 结尾钩子 | {hook} |
| 镜数 | 5 × 8秒成片 |
| 状态 | **已精修（可直接喂 H3）** |

## 分镜

| 镜 | 秒 | 事件 | 提示词 |
|----|----|------|--------|
{chr(10).join(rows)}

## 生成

1. 按镜01提示词顶部上传顺序传图（整集锁脸图不换底）  
2. 依次生成镜01→05  
3. 硬切拼接 → 超分 1080×1920 → 字幕  
"""
    (d / "单集剧本.md").write_text(md, encoding="utf-8")
    (d / "上传清单.txt").write_text(
        f"【第{ep:02d}集 · {title}】精修版\n\n"
        f"钩子：{hook}\n\n"
        "上传顺序以各镜提示词顶部为准（通常：陈岚→许舟→电梯→老周/小满）。\n"
        "只跑：镜01–05_本地成片_H3提示词.txt\n"
        "一镜只生成一次。\n",
        encoding="utf-8",
    )


def main():
    assert len(EPS) == 16, len(EPS)
    for ep, (title, hook, shots) in EPS.items():
        assert len(shots) == 5, (ep, len(shots))
        write_ep(ep, title, hook, shots)
