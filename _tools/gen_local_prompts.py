def pack(upload, refs, core_d, core_f, timeline_d, timeline_f, audio):
    return {
        "upload": upload.strip(),
        "refs": refs.strip(),
        "core_d": core_d.strip(),
        "core_f": core_f.strip(),
        "tl_d": timeline_d.strip(),
        "tl_f": timeline_f.strip(),
        "audio": audio.strip(),
    }


def render(shot, mode):
    h = HEADER_DRAFT if mode == "draft" else HEADER_FINAL
    core = shot["core_d"] if mode == "draft" else shot["core_f"]
    tl = shot["tl_d"] if mode == "draft" else shot["tl_f"]
    return f"""{h}
【上传顺序｜必须按此点选】
{shot['upload']}

【参考素材说明】
{shot['refs']}

【核心创意】
{core}

【画面过程说明】
{tl}

{shot['audio']}
"""


