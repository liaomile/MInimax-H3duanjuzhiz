def main():
    n = 0
    for (show, ep, num), shot in shots.items():
        d = ROOT / show / ep
        d.mkdir(parents=True, exist_ok=True)
        draft = render(shot, "draft")
        final = render(shot, "final")
        (d / f"镜{num}_本地草稿_H3提示词.txt").write_text(draft, encoding="utf-8")
        (d / f"镜{num}_本地成片_H3提示词.txt").write_text(final, encoding="utf-8")
        # 旧文件名指向成片，避免打开旧路径跑错
        (d / f"镜{num}_H3提示词.txt").write_text(
            "【已迁移本地双轨】请使用：\n"
            f"  镜{num}_本地草稿_H3提示词.txt  ← 5秒试跑\n"
            f"  镜{num}_本地成片_H3提示词.txt  ← 8秒成片\n\n"
            "以下为成片全文副本：\n\n" + final,
            encoding="utf-8",
        )
        n += 1
    print(f"OK shots={n} files={n*3}")


if __name__ == "__main__":
    main()
