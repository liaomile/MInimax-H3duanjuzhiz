SHOT_RE = re.compile(r"### 镜(\d+) · ([^\n]+)\n(.*?)(?=\n### 镜|\n## |\Z)", re.S)
FIELD_RE = re.compile(r"^- (画面|0[–-]2s|2[–-]5s|5[–-]8s|台词|声音|锚点|后期)：(.*)$", re.M)


def clean(s: str) -> str:
    return s.replace("**", "").strip()


def parse_episode(md: str):
    shots = []
    for m in SHOT_RE.finditer(md):
        idx = int(m.group(1))
        header = m.group(2).strip()
        body = m.group(3)
        parts = [p.strip() for p in header.split("·")]
        rest = parts[1:]  # 去掉 8s
        fields = {k: clean(v) for k, v in FIELD_RE.findall(body)}
        shots.append(
            dict(
                idx=idx,
                framing=rest[0] if rest else "中景",
                camera=rest[1] if len(rest) > 2 else "固定",
                dial=rest[-1] if rest else "无对白",
                **fields,
            )
        )
    return shots


def shot_prompt(series_key: str, shot: dict, cfg) -> str:
    scene, chars, props = cfg
    s = SERIES[series_key]
    asset_root = f"assets/{s['dir']}"

    line = shot.get("台词", "无。")
    # 只看「台词」字段判画外——时间轴里的「画外车灯」不得误判成无口型
    offscreen = bool(
        re.search(r"（画外）|\(画外\)|（电话）|\(电话\)|画外音", line)
    )

    speaker, text = None, None
    quotes = re.findall(r"「([^」]+)」", line)
    if quotes:
        head = re.match(r"^([^「]+)", line)
        speaker = (
            re.sub(r"（[^）]*）|\([^)]*\)", "", head.group(1)).strip() if head else None
        )
        # 多句合并为可念的一句串，去掉嵌在中间的引号碎片
        text = " ".join(q.strip().rstrip("。") for q in quotes)

    # 上传顺序
    uploads, refs = [], []
    files = s.get("files", {})
    noface = s.get("noface", set())
    n = 0
    for name in chars:
        n += 1
        desc, voice = s["chars"][name]
        fname = files.get(name, f"角色_{name}_正脸.jpg")
        uploads.append(f"@图片{n} = {asset_root}/角色/{fname}")
        if name in noface:
            refs.append(
                f"@图片{n} 是服装参考（锁定{name}的服装与身形：{desc}；本角色全程不给正脸，只取肩背、侧影或手部；禁止出现完整正脸特写）。"
            )
        else:
            refs.append(f"@图片{n} 是人物参考（锁定{name}：{desc}；禁止换脸换装）。")

    n += 1
    uploads.append(f"@图片{n} = {asset_root}/场景/场景_{scene}.jpg")
    refs.append(f"@图片{n} 是场景参考（{scene}：{s['scenes'][scene]}）。")

    for name in props:
        n += 1
        uploads.append(f"@图片{n} = {asset_root}/道具/道具_{name}.jpg")
        refs.append(f"@图片{n} 是物体参考（{name}：{s['props'][name]}）。")

    on_screen_voice = bool(text) and speaker in s["chars"] and not offscreen
    no_lip = "不做口型" in shot.get("后期", "")
    if text and speaker in s["chars"]:
        uploads.append(f"@音频1 = {asset_root}/音色/音色_{speaker}.wav（建议；无则用文字音色卡）")
        if offscreen or no_lip:
            refs.append(
                f"音色：{speaker}——{s['chars'][speaker][1]}；画外/气声念白，不要求口型对齐，吐字必须清楚。"
            )
        else:
            refs.append(
                f"音色：{speaker}——{s['chars'][speaker][1]}；台词必须原样说出，口型对齐，吐字清楚。"
            )

    if speaker and speaker not in s["chars"] and not offscreen:
        refs.append(f"说话者「{speaker}」为一次性配角，不做锁脸，只取侧脸/手部，不给正脸特写。")
    if offscreen and text:
        refs.append(f"「{speaker}」只有声音入画，不出现正脸、不做口型。")

    # 本镜任务
    task = shot.get("画面", "")
    if text and offscreen:
        task += f"\n本镜唯一台词（画外）：{speaker}「{text}」；只有声音，不给正脸。"
    elif text:
        task += f"\n本镜唯一台词：{speaker}说「{text}」。其他人不张嘴，只给反应。"
    else:
        task += "\n本镜无台词，靠动作、视线与声音推进。"

    has_line = bool(text)
    step = "18" if has_line else "14–16"
    dial_note = "本镜有对白" if has_line else "本镜无对白"

    beats = []
    for key, label in (("0–2s", "0–2秒"), ("2–5s", "2–5秒"), ("5–8s", "5–8秒")):
        val = shot.get(key) or shot.get(key.replace("–", "-"), "")
        if val:
            beats.append(f"{label}：{val}")

    sound = shot.get("声音", "").rstrip("。")
    anchor = shot.get("锚点", "").rstrip("。")
    post = shot.get("后期", "无特殊后期。")
    framing = shot["framing"]

    out = []
    out.append(
        f"【本地参数】8秒，9:16，约0.65兆像素，成片轨；{dial_note}，步数{step}；关闭Turbo/Lightning。"
    )
    out.append("【工作流】ComfyUI → MiniMax H3 Reference to Video（R2V）")
    out.append("【硬件】Quadro RTX 5000 16GB · --lowvram --disable-mmap")
    out.append("")
    out.append("【上传顺序｜必须按此点选】")
    out.extend(uploads)
    out.append("")
    out.append(f"【风格锁】{s['style']}")
    out.append("")
    out.append("【参考素材说明】")
    out.extend(refs)
    if not chars:
        out.append("本镜不出现人物正脸，不上传人物参考，避免多余的脸进入画面。")
    out.append("")
    out.append("【本镜任务】")
    out.append(task)
    out.append("")
    out.append("【构图与机位】")
    out.append(f"{framing}，{shot['camera']}机位，不要切镜。")
    out.append("竖屏：眉眼在上1/3；底部15%留给字幕；顶部10%保持干净。")
    if framing.startswith("特写"):
        out.append("前景：画面边缘带一点虚焦的桌面/纸边/工具边，不要把手或道具拍成证件照。")
    else:
        out.append("前景层：至少一处前景遮挡（门框/肩背/扶手/画框边），做纵深与偷看感。")
    out.append(f"轴线：{s['axis']}")
    out.append("")
    out.append("【画面过程说明】")
    out.extend(beats)
    if text and offscreen:
        out.append(f"对白（画外）：{speaker}的声音从画外进来，不需要口型；在场者只给反应。")
    elif text:
        out.append(
            f"对白：只有{speaker}开口，台词原文「{text}」；说完最后一个字不要抢下一拍。"
        )
    out.append("")
    out.append("【衔接】")
    out.append(f"首帧 = 上镜尾帧。锚点：{anchor}。")
    out.append("尾帧 = 本镜锚点所述状态，供下镜直接承接（不要回到初始站位）。")
    if text:
        out.append(f"overall_soundscape: {sound}；对白清晰，声线与角色固定对应，无配乐。")
    else:
        out.append(f"overall_soundscape: {sound}；无对白，无配乐。")
    out.append("non_diegetic_music: N/A")
    out.append(f"【后期备注】{post}")
    return "\n".join(out) + "\n"


def main():
    total, rows = 0, []
    for (series_key, ep), shots_cfg in EPISODES.items():
        ep_dir = SAMPLE / series_key / f"第{ep}集"
        if not ep_dir.exists():
            # 改编工程放在仓库根目录下（如 穿越改编_阴差/）
            alt = ROOT / series_key / f"第{ep}集"
            if alt.exists():
                ep_dir = alt
        md_path = ep_dir / "单集剧本_V4.md"
        if not md_path.exists():
            print(f"缺少 {md_path}", file=sys.stderr)
            continue
        shots = parse_episode(md_path.read_text(encoding="utf-8"))
        if len(shots) != 5:
            print(f"{md_path}: 解析到 {len(shots)} 镜（应为 5）", file=sys.stderr)

        out_dir = ep_dir / "V3_导演稿提示词"
        out_dir.mkdir(exist_ok=True)

        upl = []
        for i, shot in enumerate(shots):
            cfg = shots_cfg[i]
            text = shot_prompt(series_key, shot, cfg)
            (out_dir / f"镜{shot['idx']:02d}_V3_H3提示词.txt").write_text(text, encoding="utf-8")
            total += 1

            scene, chars, props = cfg
            ups = [f"{c}=@图片{n+1}" for n, c in enumerate(chars)]
            ups.append(f"场景={scene}")
            if props:
                ups.append("道具=" + "/".join(props))
            upl.append(
                f"镜{shot['idx']:02d}｜{shot['framing']}｜{shot['dial']}｜" + "，".join(ups)
            )
            line = shot.get("台词", "无")
            rows.append((f"{series_key}/第{ep}集", shot["idx"], shot["framing"], 0 if line.startswith("无") else 1, len(text)))

        (out_dir / "00_上传顺序.txt").write_text(
            f"# 第{ep}集 V3 上传顺序\n\n" + "\n".join(upl) + "\n", encoding="utf-8"
        )

    print(f"generated {total} prompts")
    for r in rows:
        print(r[0], r[1], r[2], "dialogue" if r[3] else "-", f"{r[4]}B")


if __name__ == "__main__":
    main()
